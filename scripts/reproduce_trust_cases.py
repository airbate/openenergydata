#!/usr/bin/env python3
"""Generate small, explicitly synthetic reproductions of three observed failures."""
import argparse
import json
from pathlib import Path
import pandas as pd
from oed.io import sha256_file,write_manifest
from oed.trust import check_inputs,write_check_report
from oed.converters.common import DatasetBuilder
from oed.quality.scanner import scan_channel,ScanConfig
from oed.units import watts_factor


def main(output):
    output.mkdir(parents=True,exist_ok=True)
    times=pd.date_range('2013-01-01',periods=3,freq='30min',tz='UTC')
    frame=pd.DataFrame({'DateTime':times,'LCLid':['MAC000001']*3,'KWH/hh':[1.,30.,1.]})
    text=output/'text-ids.feather';frame.to_feather(text)
    numeric=output/'numeric-ids.feather';frame.assign(LCLid=[0,0,0]).to_feather(numeric)
    broken=output/'truncated.feather';broken.write_bytes(text.read_bytes()[:-20])
    cases={
        '01-truncated':check_inputs([broken],expected_hashes={broken.name:sha256_file(broken)}),
        '02-identities':check_inputs([text,numeric],expected_hashes={p.name:sha256_file(p) for p in [text,numeric]}),
    }
    root=output/'energy-dataset'
    builder=DatasetBuilder(root,name='synthetic-energy-case',description='Synthetic reproduction, not a measured LCL anomaly',source_url='https://example.org/synthetic',source_license='CC0-1.0',citation='Generated by reproduce_trust_cases.py',dataset_id='synthetic')
    channel={'id':'energy','path':'sites/demo/energy.parquet','role':'site_meter',
             'physical_quantity':'energy','ac_type':'active','unit':'kWh','nominal_interval_s':1800}
    data=pd.DataFrame({'timestamp':times,'power_w':[1.,30.,1.],'quality':[0,0,0]})
    builder.add_channel('demo',channel,data)
    builder.add_site({'id':'demo','timezone':'UTC','channels':[channel]})
    manifest=builder.build()
    value_field=next(f for f in manifest['recordSet'][0]['field'] if f['name']=='power_w')
    value_field['description']='W'
    write_manifest(manifest,root)
    cases['03-units-before']=check_inputs([],root)
    value_field['description']='kWh'
    write_manifest(manifest,root)
    cases['03-units-after']=check_inputs([],root)
    evidence={'fixture_kind':'synthetic, not an observed LCL outlier',
              'input':{'value':30,'unit':'kWh','interval_seconds':1800},
              'legacy_raw_comparison_exceeds_50000':bool(30>50000),
              'converted_watts':30*watts_factor(channel),
              'corrected_findings':scan_channel(data,channel,ScanConfig())}
    (output/'unit-calculation.json').write_text(json.dumps(evidence,ensure_ascii=False,indent=2))
    for name,report in cases.items():
        write_check_report(report,output/name)
    assert cases['01-truncated']['status']=='fail'
    assert cases['02-identities']['status']=='fail'
    assert cases['03-units-before']['status']=='fail'
    assert cases['03-units-after']['status']=='review_required'
    assert any(f['type']=='outlier' for f in evidence['corrected_findings'])
    print(json.dumps({name:report['status'] for name,report in cases.items()},indent=2))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=Path('cases/reproduced'))
    main(parser.parse_args().output)
